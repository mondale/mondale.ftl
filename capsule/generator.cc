ResultOr<std::string> GenerateHeader(const CapsuleFile& file) {
  std::ostringstream oss;
  oss << "// Generated by Capsule Compiler\n";
  oss << "#pragma once\n\n";
  oss << "#include <cstdint>\n";
  oss << "#include <memory>\n";
  oss << "#include <string>\n";
  oss << "#include <vector>\n";
  oss << "#include \"capsule/decoder.h\"\n";
  oss << "#include \"capsule/encoder.h\"\n";
  oss << "#include \"capsule/size_builder.h\"\n";
  oss << "#include \"capsule/storage.h\"\n";
  oss << "#include \"capsule/text/parsing_widget.h\"\n";
  oss << "#include \"capsule/text/text_parser.h\"\n";
  oss << "#include \"core/vocabulary.h\"\n\n";
  oss << "namespace " << file.namespace_name << " {\n\n";

  // Struct forward declarations.
  for (const auto& cp : file.capsules) {
    oss << "struct " << cp.name << "M;\n";
    oss << "struct " << cp.name << "V;\n";
  }
  oss << "\n";

  // Struct base classes.
  for (const auto& cp : file.capsules) {
    oss << "struct " << cp.name << "Base {\n";
    oss << "  using MaterializedType = " << cp.name << "M;\n";
    oss << "  using ViewType = " << cp.name << "V;\n";
    oss << "\n";
    oss << "  static constexpr ::core::CRC32C kTypeHash = ::core::CRC32C(0x"
        << std::hex << cp.hash.value() << "u);\n";
    oss << "  static constexpr uint32_t kFieldCount = "
        << CountNonRetiredFields(cp) << ";\n";

    // Field hashes.
    for (int i = 0; i < cp.fields.size(); ++i) {
      const auto& f = cp.fields[i];
      if (FieldIsRetired(f)) continue;
      if (f.hashes.empty()) {
        return Result(Code::kInvalidArgument,
                      strings::Format("Field {} missing hashes.", f.name));
      }
      oss << "  static constexpr ::core::CRC32C " << f.name
          << "_FieldHash = ::core::CRC32C(0x" << std::hex << f.hashes[0].value()
          << "u);\n";
      for (int i = 1; i < f.hashes.size(); ++i) {
        oss << "  static constexpr ::core::CRC32C " << f.name << "_FieldHash"
            << i << " = ::core::CRC32C(0x" << std::hex << f.hashes[i].value()
            << "u);\n";
      }
    }

    // Field defaults.
    for (int i = 0; i < cp.fields.size(); ++i) {
      const auto& f = cp.fields[i];
      if (!DefaultValueSupported(f)) continue;
      if (FieldIsRetired(f)) continue;
      oss << "  static constexpr " << MapType(f.type) << " " << f.name
          << "_Default = " << CppDefaultValue(f) << ";\n";
    }

    // Field indexes.
    for (int i = 0; i < cp.fields.size(); ++i) {
      const auto& f = cp.fields[i];
      if (FieldIsRetired(f)) continue;
      oss << "  static constexpr int " << f.name << "_Index = " << i << ";\n";
    }

    oss << "\n";

    // The ever-lovely has_ family of accessors.
    for (int i = 0; i < cp.fields.size(); ++i) {
      const auto& f = cp.fields[i];
      if (FieldIsRetired(f)) continue;
      oss << "  bool has_" << f.name << "() const { return has_[" << f.name
          << "_Index]; }\n";
    }
    oss << "  bool has() const { return !has_.empty(); }\n";

    oss << "\n";
    oss << "  std::vector<bool> has_;\n";

    oss << "};\n";
    oss << "\n";
  }

  // Materialized structs.
  for (const auto& cp : file.capsules) {
    oss << "struct " << cp.name << "M : public " << cp.name << "Base {\n";
    for (const auto& f : cp.fields) {
      if (FieldIsRetired(f)) continue;
      oss << "  " << MapType(f.type) << " " << f.name << ";\n";
    }
    oss << "\n";
    oss << "  size_t ComputeStorageSize() const;\n";
    oss << "  void Encode(::capsule::Encoder* e) const;\n";
    oss << "  ::core::Result Decode(::capsule::Decoder* d);\n";
    oss << "  std::string ToString(int indent = 0) const;\n";
    oss << "  ::core::Result ParseFrom(::capsule::text::TextParser* p);\n";
    oss << "};\n\n";
  }

  // View structs.
  for (const auto& cp : file.capsules) {
    oss << "struct " << cp.name << "V : public " << cp.name << "Base {\n";
    for (const auto& f : cp.fields) {
      if (FieldIsRetired(f)) continue;
      oss << "  " << TypeToViewType(f.type) << " " << f.name << ";\n";
    }
    oss << "\n";
    if (RefsStorage(cp)) {
      oss << "  std::unique_ptr<::capsule::Storage> ref_;\n\n";
    }
    oss << "  ::core::Result Decode(::capsule::Decoder* d);\n";
    oss << "  void RefIfNeeded(::capsule::Storage* s);\n";
    oss << "  std::string ToString(int indent = 0) const;\n";
    oss << "};\n\n";
  }

  oss << "}  // namespace " << file.namespace_name << "\n";
  return oss.str();
}

Result EmitDecodeImpl(std::ostringstream& oss, std::string_view class_postfix,
                      const capsule::Capsule& cp) {
  oss << "::core::Result " << cp.name << class_postfix
      << "::Decode(::capsule::Decoder* d) {\n";
  oss << "  has_.resize(kFieldCount, false);\n";
  oss << "  ::core::Code ret = ::core::Code::kOk;\n";
  for (int i = 0; i < cp.fields.size(); ++i) {
    const auto& f = cp.fields[i];
    if (FieldIsRetired(f)) continue;
    const auto& n = f.name;
    const auto& t = f.type;
    // Find, FindCapsule, FindCapsuleVector, FindStringVector are distinct
    // APIs on Decode b/c I am bad at templates.
    oss << "  ";
    auto emit = [&](const std::string& fh) {
      if (IsCapsuleVectorType(t)) {
        oss << "ret.Incorporate(d->FindCapsuleVector(" << fh << ", &" << n
            << ", has_[" << n << "_Index]));\n";
      } else if (IsStringVectorType(t)) {
        oss << "ret.Incorporate(d->FindStringVector(" << fh << ", &" << n
            << ", has_[" << n << "_Index]));\n";
      } else if (IsCapsuleType(t)) {
        oss << "ret.Incorporate(d->FindCapsule(" << fh << ", &" << n
            << ", has_[" << n << "_Index]));\n";
      } else {  // primitive type
        oss << "ret.Incorporate(d->Find<decltype(" << n << ")>(" << fh << ", &"
            << n << ", " << n << "_Default, has_[" << n << "_Index]));\n";
      }
    };
    emit(n + "_FieldHash");

    // Support for formerly attribute.
    for (int i = 1; i < f.hashes.size(); ++i) {
      // if (!has_[foo_Index]) ret.Incor(... FieldHash1);
      oss << "  if (!has_[" << n << "_Index]) ";
      std::string fhi = strings::Format("{}_FieldHash{}", n, i);
      emit(fhi);
    }
  }
  oss << "  return ret;\n";
  oss << "}\n\n";
  return Result::Ok();
}

Result EmitToStringImpl(std::ostringstream& oss, std::string_view class_postfix,
                        const capsule::Capsule& cp) {
  oss << "std::string " << cp.name << class_postfix
      << "::ToString(int indent) const {\n";
  oss << "  std::ostringstream oss;\n";
  for (const auto& f : cp.fields) {
    if (FieldIsRetired(f)) continue;
    if ("string" == f.type) {
      oss << "  if(!has() || has_" << f.name
          << "()) oss << std::string(indent, ' ') << \"" << f.name
          << ": \\\"\" << " << f.name << " << \"\\\"\" << std::endl;\n";
    } else if (IsPrimitiveType(f.type)) {
      oss << "  if(!has() || has_" << f.name
          << "()) oss << std::string(indent, ' ') << \"" << f.name
          << ": \" << ";
      if (Is8bPrintingHazardType(f.type)) {
        oss << "static_cast<int>(" << f.name << ") << std::endl;\n";
      } else {
        oss << f.name << " << std::endl;\n";
      }
    } else if (IsCapsuleType(f.type)) {
      oss << "  if (!has() || has_" << f.name << "()) {\n";
      oss << "    oss << \" {\" << std::endl;\n";
      oss << "    oss << " << f.name << ".ToString(indent + 2);\n";
      oss << "    oss << std::string(indent, ' ') << \"}\" << std::endl;\n";
      oss << "  }\n";
    } else if (IsStringVectorType(f.type)) {
      oss << "  if ((!has() || has_" << f.name << "()) && !" << f.name
          << ".empty()) {\n";
      oss << "    oss << std::string(indent, ' ') << \"" << f.name
          << " {\" << std::endl;\n";
      oss << "    for (const auto& s : " << f.name << ") {\n";
      oss << "      oss << std::string(indent + 2, ' ') << \"\\\"\" << s << "
             "\"\\\"\" << std::endl;\n";
      oss << "    }\n";
      oss << "    oss << std::string(indent, ' ') << \"}\" << std::endl;\n";
      oss << "  }\n";
    } else if (IsCapsuleVectorType(f.type)) {
      oss << "  if ((!has() || has_" << f.name << "()) && !" << f.name
          << ".empty()) {\n";
      oss << "    oss << std::string(indent, ' ') << \"" << f.name
          << "[] {\" << std::endl;\n";
      oss << "    for (const auto& elem : " << f.name << ") {\n";
      oss << "      oss << \" {\" << std::endl;\n";
      oss << "      oss << elem.ToString(indent + 2);\n";
      oss << "      oss << std::string(indent, ' ') << \"}\";\n";
      oss << "    }\n";
      oss << "    oss << std::endl;\n";
      oss << "  }\n";
    } else {
      return core::UnimplementedError(
          strings::Format("No ToString for type [{}].", f.type));
    }
  }
  oss << "  return oss.str();\n";
  oss << "}\n\n";
  return Result::Ok();
}

Result EmitParseFromImpl(std::ostringstream& oss, const capsule::Capsule& cp) {
  oss << "::core::Result " << cp.name
      << "M::ParseFrom(::capsule::text::TextParser* p) {\n";
  oss << "  ::capsule::text::ParsingWidget w;\n";
  for (const auto& f : cp.fields) {
    if (FieldIsRetired(f)) continue;
    if (IsCapsuleType(f.type)) {
      oss << "  w.AddCapsule(\"" << f.name << "\", [this](auto* p) { return "
          << f.name << ".ParseFrom(p); });\n";
    } else if (IsCapsuleVectorType(f.type)) {
      oss << "  w.AddCapsuleVector(\"" << f.name
          << "\", [this](auto* p) { return " << f.name
          << ".emplace_back().ParseFrom(p); });\n";
    } else if (IsStringVectorType(f.type)) {
      oss << "  w.AddStringVector(\"" << f.name << "\", &" << f.name << ");\n";
    } else {
      oss << "  w.Add(\"" << f.name << "\", &" << f.name << ");\n";
    }
  }
  oss << "  return w.ParseFrom(p);\n";
  oss << "}\n\n";
  return Result::Ok();
}

ResultOr<std::string> GenerateSource(const CapsuleFile& file,
                                     std::string_view header_location) {
  std::ostringstream oss;
  oss << "// Generated by Capsule Compiler\n";
  oss << "#include \"" << header_location << "\"\n";
  oss << "#include <ostream>\n";
  oss << "\n";
  oss << "namespace " << file.namespace_name << " {\n\n";

  // ComputeStorageSize() impls (Materialized types only).
  for (const auto& cp : file.capsules) {
    oss << "size_t " << cp.name << "M::ComputeStorageSize() const {\n";
    oss << "  ::capsule::SizeBuilder sb;\n";
    for (int i = 0; i < cp.fields.size(); ++i) {
      const auto& f = cp.fields[i];
      if (FieldIsRetired(f)) continue;
      oss << "  sb.Add(" << f.name << ");\n";
    }
    oss << "  return sb.Build();\n";
    oss << "}\n\n";
  }

  // Encode() impls (Materialized types only).
  for (const auto& cp : file.capsules) {
    oss << "void " << cp.name << "M::Encode(::capsule::Encoder* e) const {\n";
    for (int i = 0; i < cp.fields.size(); ++i) {
      const auto& f = cp.fields[i];
      if (FieldIsRetired(f)) continue;
      // AddCapsuleVector is a distinct API in Encoder, probably because I'm bad
      // at templates.
      if (IsCapsuleVectorType(f.type)) {
        oss << "  e->AddCapsuleVector(";
      } else {
        oss << "  e->Add(";
      }
      oss << f.name << "_FieldHash, " << f.name << ");\n";
    }
    oss << "}\n\n";
  }

  // Decode() impls (Materialized and View types).
  for (const auto& cp : file.capsules) {
    TRY(EmitDecodeImpl(oss, "M", cp));
    TRY(EmitDecodeImpl(oss, "V", cp));
  }

  // RefIfNeeded impls (View types only).
  for (const auto& cp : file.capsules) {
    oss << "void " << cp.name << "V::RefIfNeeded(::capsule::Storage* s) {\n";
    if (RefsStorage(cp)) {
      oss << "  ref_ = s->Ref();\n";
    }
    oss << "}\n\n";
  }

  // ToString() impls (Materialied and View types).
  for (const auto& cp : file.capsules) {
    TRY(EmitToStringImpl(oss, "M", cp));
    TRY(EmitToStringImpl(oss, "V", cp));
  }

  // ParseFrom() impls (Materialized types only).
  for (const auto& cp : file.capsules) {
    TRY(EmitParseFromImpl(oss, cp));
  }

  oss << "}  // namespace " << file.namespace_name << "\n";
  return oss.str();
}

