std::string MapType(const std::string& tp) {
  if (tp == "u64") return "uint64_t";
  if (tp == "u32") return "uint32_t";
  if (tp == "u16") return "uint16_t";
  if (tp == "u8") return "uint8_t";
  if (tp == "i64") return "int64_t";
  if (tp == "i32") return "int32_t";
  if (tp == "i16") return "int16_t";
  if (tp == "i8") return "int8_t";
  if (tp == "f64") return "double";
  if (tp == "f32") return "float";
  if (tp == "bool") return "bool";
  if (tp == "string") return "std::string";
  if (tp.rfind("vector<", 0) == 0) {
    std::string inner = tp.substr(7, tp.size() - 8);
    return "std::vector<" + MapType(inner) + ">";
  }
  return tp + "M";
}

std::string TypeToViewType(const std::string& tp) {
  if (tp == "u64") return "uint64_t";
  if (tp == "u32") return "uint32_t";
  if (tp == "u16") return "uint16_t";
  if (tp == "u8") return "uint8_t";
  if (tp == "i64") return "int64_t";
  if (tp == "i32") return "int32_t";
  if (tp == "i16") return "int16_t";
  if (tp == "i8") return "int8_t";
  if (tp == "f64") return "double";
  if (tp == "f32") return "float";
  if (tp == "bool") return "bool";
  if (tp == "string") return "std::string_view";
  if (tp.rfind("vector<string>", 0) == 0) {
    return "std::vector<std::string_view>";
  }
  if (tp.rfind("vector<", 0) == 0) {
    std::string inner = tp.substr(7, tp.size() - 8);
    return "std::vector<" + TypeToViewType(inner) + ">";
  }
  return tp + "V";
}

bool Is8bPrintingHazardType(const std::string& t) {
  return t == "u8" || t == "i8";
}

std::string CppDefaultForType(const std::string& tp) {
  if (tp == "bool") return "false";
  if (tp == "string") return "";
  if (tp == "f64") return "0.0";
  if (tp == "f32") return "0.0";
  return "0";
}

std::string CppDefaultValue(const Field& f) {
  std::string d;
  for (const auto& a : f.attributes) {
    if (a.name != "default") continue;
    d = a.value;
  }
  if (d.empty()) d = CppDefaultForType(f.type);
  if (f.type == "string") {
    d = "\"" + d + "\"";
  }
  return d;
}

bool IsVectorType(const std::string& tp) { return tp.rfind("vector<", 0) == 0; }

bool IsStringVectorType(const std::string& tp) {
  return tp.rfind("vector<string>", 0) == 0;
}

bool IsCapsuleVectorType(const std::string& tp) {
  return IsVectorType(tp) && !IsStringVectorType(tp);
}

bool IsCapsuleType(const std::string& tp) { return MapType(tp) == (tp + "M"); }

bool DefaultValueSupported(const Field& f) {
  return !IsVectorType(f.type) && !IsCapsuleType(f.type);
}

bool IsPrimitiveType(const std::string& t) {
  return !IsVectorType(t) && !IsCapsuleType(t);
}

bool FieldHasAttr(const Field& f, std::string_view attr) {
  for (const auto& a : f.attributes) {
    if (a.name == attr) return true;
  }
  return false;
}

bool FieldIsRetired(const Field& f) { return FieldHasAttr(f, "retired"); }

int CountNonRetiredFields(const Capsule& c) {
  int count = 0;
  for (const auto& f : c.fields) {
    if (!FieldIsRetired(f)) count++;
  }
  return count;
}

bool RefsStorage(const Capsule& c) {
  for (const auto& f : c.fields) {
    if (FieldIsRetired(f)) continue;
    if (f.type == "string" || f.type == "vector<string>") return true;
  }
  return false;
}

